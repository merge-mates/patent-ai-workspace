import pytest

from src.rag.display import render_answer

EV = [{"tag": "E1", "label": "특허법 제30조"}, {"tag": "E2", "label": "특허법 시행령 제5조"},
      {"tag": "E3", "label": "특허법 제81조"}]


@pytest.mark.parametrize("raw,expected", [
    # 괄호 안에 이미 조문을 말하고 있으면 꼬리표만 지운다
    ("공지가 아닌 것으로 봅니다(특허법 제30조제1항, E1).", "공지가 아닌 것으로 봅니다(특허법 제30조제1항)."),
    ("대통령령에 따릅니다(제38조제4항, E2).", "대통령령에 따릅니다(제38조제4항)."),
    # 꼬리표만 있으면 조문 이름으로 바꾸고 뒤의 항 표시는 살린다
    ("추가납부할 수 있습니다(E3 ①②).", "추가납부할 수 있습니다(특허법 제81조 ①②)."),
    ("(E1, E2)", "(특허법 제30조, 특허법 시행령 제5조)"),
    ("확인된다[E1].", "확인된다[특허법 제30조]."),
    ("(E1, E1)", "(특허법 제30조)"),
    # 괄호 밖 꼬리표(한글 조사가 붙은 경우 포함)
    ("E2는 기탁을 규정합니다.", "특허법 시행령 제5조는 기탁을 규정합니다."),
    ("E1에 따르면 12개월입니다.", "특허법 제30조에 따르면 12개월입니다."),
    # 근거에 없는 꼬리표는 지운다(빈 괄호가 남지 않게)
    ("답입니다 (E9).", "답입니다."),
    ("(E1, E9)", "(특허법 제30조)"),
    # 꼬리표가 없으면 그대로(개정 표기·굵게 포함)
    ("**결론:** <개정 2020.3.24.> 그대로 둡니다.", "**결론:** <개정 2020.3.24.> 그대로 둡니다."),
    ("", ""),
])
def test_render_answer(raw, expected):
    assert render_answer(raw, EV) == expected


def test_words_that_merely_contain_e_digit_are_not_tags():
    assert render_answer("SE1 및 E1x 와 PE2", EV) == "SE1 및 E1x 와 PE2"
